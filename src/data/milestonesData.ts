import {
  UserProfile,
  SyllabusTopic,
  MainsAnswerEvaluation,
  MilestoneBadge,
} from "../types";

export function generateMilestones(
  user: UserProfile,
  topics: SyllabusTopic[],
  evaluations: MainsAnswerEvaluation[] = []
): MilestoneBadge[] {
  const completedTopicsCount = topics.filter((t) => t.completionPercentage >= 80).length;
  const streak = user.studyStreakDays || 0;
  const totalHours = user.totalStudyHours || 0;
  const questionsCount = user.questionsAttempted || 0;
  const mainsCount = evaluations.length || user.mainsEvaluatedCount || 0;
  const maxScore = evaluations.length > 0 ? Math.max(...evaluations.map((e) => e.score)) : 0;

  return [
    {
      id: "ms-first-steps",
      title: "First Steps to Mussoorie",
      description: "Complete your initial 5 hours of structured UPSC syllabus coverage.",
      category: "syllabus_milestone",
      badgeLevel: "Bronze",
      iconName: "book-open",
      isUnlocked: totalHours >= 5,
      progress: Math.min(100, Math.round((totalHours / 5) * 100)),
      criteria: "Log 5 hours of focused study",
      currentValue: totalHours,
      targetValue: 5,
      rewardXp: 100,
    },
    {
      id: "ms-discipline-streak-7",
      title: "Consistent Aspirant",
      description: "Maintain an unbroken 7-day daily study streak.",
      category: "streak",
      badgeLevel: "Bronze",
      iconName: "flame",
      isUnlocked: streak >= 7,
      progress: Math.min(100, Math.round((streak / 7) * 100)),
      criteria: "7-day study streak",
      currentValue: streak,
      targetValue: 7,
      rewardXp: 150,
    },
    {
      id: "ms-discipline-streak-30",
      title: "Iron Will (30-Day Streak)",
      description: "Sustain disciplined daily study for 30 consecutive days without lapse.",
      category: "streak",
      badgeLevel: "Silver",
      iconName: "flame",
      isUnlocked: streak >= 30,
      progress: Math.min(100, Math.round((streak / 30) * 100)),
      criteria: "30-day study streak",
      currentValue: streak,
      targetValue: 30,
      rewardXp: 500,
    },
    {
      id: "ms-prelims-century",
      title: "Centurion (100 MCQs)",
      description: "Solve and review 100 UPSC Prelims practice questions and PYQs.",
      category: "high_score",
      badgeLevel: "Bronze",
      iconName: "target",
      isUnlocked: questionsCount >= 100,
      progress: Math.min(100, Math.round((questionsCount / 100) * 100)),
      criteria: "Attempt 100 practice MCQs",
      currentValue: questionsCount,
      targetValue: 100,
      rewardXp: 200,
    },
    {
      id: "ms-prelims-accuracy-high",
      title: "Elimination Master",
      description: "Attain an overall accuracy of 75% or higher on Prelims questions.",
      category: "high_score",
      badgeLevel: "Silver",
      iconName: "zap",
      isUnlocked: (user.overallAccuracy || 0) >= 75 && questionsCount >= 20,
      progress: Math.min(100, Math.round(((user.overallAccuracy || 0) / 75) * 100)),
      criteria: ">=75% accuracy with min. 20 questions",
      currentValue: `${user.overallAccuracy || 0}%`,
      targetValue: "75%",
      rewardXp: 300,
    },
    {
      id: "ms-unit-completion-5",
      title: "Core Foundation Builder",
      description: "Master at least 5 syllabus units with >=80% completion score.",
      category: "unit_completion",
      badgeLevel: "Silver",
      iconName: "check-circle",
      isUnlocked: completedTopicsCount >= 5,
      progress: Math.min(100, Math.round((completedTopicsCount / 5) * 100)),
      criteria: "Complete 5 syllabus topics (>=80%)",
      currentValue: completedTopicsCount,
      targetValue: 5,
      rewardXp: 350,
    },
    {
      id: "ms-unit-completion-15",
      title: "Syllabus Conqueror",
      description: "Master 15 full syllabus topics across Paper 1 and Paper 2.",
      category: "unit_completion",
      badgeLevel: "Gold",
      iconName: "award",
      isUnlocked: completedTopicsCount >= 15,
      progress: Math.min(100, Math.round((completedTopicsCount / 15) * 100)),
      criteria: "Complete 15 syllabus topics (>=80%)",
      currentValue: completedTopicsCount,
      targetValue: 15,
      rewardXp: 750,
    },
    {
      id: "ms-mains-evaluator-first",
      title: "Answer Writing Initiation",
      description: "Submit your first Mains answer for multi-dimensional rubric evaluation.",
      category: "mains_mastery",
      badgeLevel: "Bronze",
      iconName: "trophy",
      isUnlocked: mainsCount >= 1,
      progress: mainsCount >= 1 ? 100 : 0,
      criteria: "Evaluate 1 Mains answer",
      currentValue: mainsCount,
      targetValue: 1,
      rewardXp: 150,
    },
    {
      id: "ms-mains-distinction",
      title: "Mains 10+ Marks Distinction",
      description: "Score 10.0 or higher out of 15 on an evaluated UPSC Mains answer.",
      category: "mains_mastery",
      badgeLevel: "Gold",
      iconName: "star",
      isUnlocked: maxScore >= 10,
      progress: Math.min(100, Math.round((maxScore / 10) * 100)),
      criteria: "Achieve >=10/15 on any Mains evaluation",
      currentValue: maxScore > 0 ? `${maxScore}/15` : "0/15",
      targetValue: "10/15",
      rewardXp: 600,
    },
    {
      id: "ms-deep-work-century",
      title: "Century of Deep Work (100 Hours)",
      description: "Accumulate 100 hours of disciplined focus timer study sessions.",
      category: "syllabus_milestone",
      badgeLevel: "Platinum",
      iconName: "award",
      isUnlocked: totalHours >= 100,
      progress: Math.min(100, Math.round((totalHours / 100) * 100)),
      criteria: "Accumulate 100 study hours",
      currentValue: `${totalHours} hrs`,
      targetValue: "100 hrs",
      rewardXp: 1000,
    },
  ];
}
